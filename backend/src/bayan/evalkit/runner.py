"""Builds the judge scoreboard from the lanes' own evaluation functions.

Run `uv run python scripts/run_evaluation.py` to regenerate `bayan/data/scoreboard.json`. The API
serves that committed artefact; it never runs a long evaluation inside a request. Every metric
states how it was measured and what it does not show.
"""

from __future__ import annotations

import importlib
import math
from collections.abc import Callable
from datetime import UTC, datetime
from typing import Any

from bayan.evalkit.models import Metric, Scoreboard

ENGINE_N = 20_000
SEED = 20261120


def _wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95% Wilson score interval; for k == n the exact one-sided bound 0.025**(1/n) is used."""
    if n == 0:
        return (0.0, 1.0)
    if k == n:
        return (0.025 ** (1.0 / n), 1.0)
    p = k / n
    denom = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / denom
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / denom
    return (max(0.0, centre - half), min(1.0, centre + half))


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%" if x < 0.9995 else "100%"


def engine_metrics(n: int = ENGINE_N, seed: int = SEED) -> list[Metric]:
    from bayan.genetics.evaluation import run_engine_evaluation

    rep = run_engine_evaluation(n, seed)
    lo, hi = _wilson(rep.agreement_agree, rep.agreement_total)
    rm = rep.random_mating
    published = (
        "; ".join(f"{p.label}: {p.value_pct}%" for p in rm.published_context)
        if rm.published_context
        else "see report"
    )
    return [
        Metric(
            id="M1",
            title="Result engine versus an independent oracle",
            status="measured",
            value=f"{rep.agreement_agree:,} of {rep.agreement_total:,} synthetic couples agree ({_pct(rep.agreement_rate)})",
            numeric=rep.agreement_rate,
            n=rep.agreement_total,
            interval=(lo, hi),
            method=(
                "Couples are generated by gene dropping through unrelated, second-cousin, "
                "first-cousin-once-removed, first-cousin and double-first-cousin pedigrees with ground-truth "
                "genotypes. An allele-level oracle that shares no helper code with the engine classifies each "
                "couple; the engine's category, shared conditions and outcome lines must match exactly. "
                f"Ruleset {rep.ruleset_version}; seed {rep.seed}."
            ),
            does_not_show=(
                "Agreement between two implementations written by the same team. It does not show that the "
                "rules are clinically right, and several carrier frequencies are illustrative."
            ),
            seed=rep.seed,
            command=f"uv run python scripts/run_evaluation.py  (engine n={n})",
        ),
        Metric(
            id="M1b",
            title="Random-mating at-risk rate against the closed form",
            status="measured",
            value=(
                f"observed {rm.observed_autosomal_at_risk_rate * 100:.2f}% against closed form "
                f"{rm.closed_form_autosomal_at_risk_rate * 100:.2f}% (autosomal loci of the demo panel)"
            ),
            numeric=rm.observed_autosomal_at_risk_rate,
            n=rm.couples,
            method=(
                "Unrelated couples drawn under Hardy-Weinberg; the share with at least one autosomal locus "
                "where both carry a pathogenic allele, compared with the independent closed form. Published "
                f"figures are shown as context only: {published}."
            ),
            does_not_show=(
                "A bracket, not a validation: the demo panel is small and illustrative, and the published "
                "programme figures use different panels and definitions."
            ),
            seed=rep.seed,
        ),
    ]


def explain_metrics() -> list[Metric]:
    from bayan.explain.evaluation import run_explain_evaluation

    r = run_explain_evaluation()
    return [
        Metric(
            id="M2",
            title="Numeric fidelity, polarity and banned words in rendered explanations",
            status="measured",
            value=(
                f"{r.documents_checked:,} documents ({r.scenarios} scenarios, {len(r.locales)} languages): "
                f"numbers {r.numeric_fidelity_pct:.0f}%, polarity {r.polarity_pct:.0f}%, "
                f"banned words absent {r.banned_words_absent_pct:.0f}%"
            ),
            numeric=r.numeric_fidelity_pct / 100,
            n=r.documents_checked,
            method=(
                "Every scenario is rendered in English, Arabic and Urdu from reviewed templates, then "
                "checked: every number equals an engine number, the text says what the engine said, and no "
                "banned wording appears."
            ),
            does_not_show=(
                "That the wording is clear to a real person, or correct in Arabic and Urdu: those texts are "
                "machine-drafted and no native clinical reviewer has read them."
            ),
        ),
        Metric(
            id="M2b",
            title="Does the checker catch injected faults?",
            status="measured",
            value=f"{r.mutants_caught:,} of {r.mutants_generated:,} injected faults caught ({r.mutation_catch_rate_pct:.0f}%)",
            numeric=r.mutation_catch_rate_pct / 100,
            n=r.mutants_generated,
            method="Flipped numbers, flipped polarity and inserted banned words are injected into rendered text; the checker must reject each.",
            does_not_show="Only the fault types listed in the method; a fault of a kind we did not think of would not be counted here.",
        ),
        Metric(
            id="M3",
            title="Readability of the English text",
            status="measured",
            value=f"Flesch-Kincaid grade {r.english_fk_grade_mean:.1f} on average, {r.english_fk_grade_max:.1f} at most",
            numeric=r.english_fk_grade_mean,
            method="Flesch-Kincaid grade computed on every rendered English document.",
            does_not_show=f"Understanding. {r.arabic_urdu_readability}",
        ),
    ]


def escalation_metrics() -> list[Metric]:
    from bayan.governance.escalation_eval import run_escalation_evaluation

    r = run_escalation_evaluation()
    return [
        Metric(
            id="M4",
            title="Escalation triggers: recall and precision on a generated edge-case set",
            status="measured",
            value=(
                f"recall {r.recall * 100:.0f}% ({r.true_positive} of {r.n_positive} must-escalate cases); "
                f"precision {r.precision_easy * 100:.0f}% on easy negatives, "
                f"{r.precision_with_hard * 100:.0f}% including hard negatives"
            ),
            numeric=r.recall,
            n=r.n_positive,
            method="Must-escalate and must-not-escalate cases are generated deterministically from the trigger definitions.",
            does_not_show=r.caveat,
            seed=r.seed,
        )
    ]


def optional_metrics() -> list[Metric]:
    """Metrics from callables another lane may expose; each is skipped, not faked, when absent."""
    out: list[Metric] = []
    for module, fn, adapter in (
        ("bayan.governance.property_eval", "run_disclosure_property_evaluation", _disclosure),
        ("bayan.governance.refusal_eval", "run_refusal_evaluation", _refusal),
    ):
        try:
            callable_: Callable[[], Any] = getattr(importlib.import_module(module), fn)
        except (ImportError, AttributeError):
            continue
        out.extend(adapter(callable_()))
    return out


def _disclosure(r: Any) -> list[Metric]:
    return [
        Metric(
            id="M5",
            title="Disclosure properties against an independent reference model",
            status="measured",
            value=(
                f"{r.sequences:,} randomised sequences, {r.decisions:,} disclosure decisions "
                f"({r.allowed:,} allowed, {r.denied:,} denied): {r.mismatches} mismatches with the "
                f"reference model, {r.leak_scans:,} leak scans clean; {r.mutants_killed} of "
                f"{r.mutants_total} deliberately broken rule sets caught"
            ),
            numeric=0.0 if r.mismatches else 1.0,
            n=r.decisions,
            method=(
                "Random sequences of roles, grants, revocations, expiries, right-not-to-know and policy "
                "choices. Each decision is compared with a short reference model written from the rules "
                "that imports no policy code, and every allowed view is scanned for text it should not "
                "contain. Deliberately broken rule sets (mutants) must each be caught."
            ),
            does_not_show=(
                "That the rules are legally complete. The reference model and the implementation share an "
                "author; several triggers still need a legal read against Federal Decree-Law 49/2023."
            ),
            seed=r.seed,
            command="uv run python scripts/run_evaluation.py  (disclosure run is 2,000 sequences)",
        )
    ]


def _refusal(r: Any) -> list[Metric]:
    first = r.heldout_first_run_frozen
    dev = r.dev_tuned
    return [
        Metric(
            id="M6",
            title="Refusal compliance on a labelled prompt set (English, Arabic, Urdu)",
            status="measured",
            value=(
                f"held-out set, first run before any tuning: {first.refused} of {first.must_refuse} "
                f"refused ({first.recall * 100:.0f}%), {first.false_refusals} of {first.benign} benign "
                f"prompts wrongly refused; tuned set: {dev.refused} of {dev.must_refuse} refused "
                f"({r.n_prompts} prompts in total)"
            ),
            numeric=first.recall,
            n=first.must_refuse,
            method=(
                "Keyword and pattern matching on prompts that ask for a diagnosis, whether to marry or "
                "cancel, termination advice, lineage inference, or employer or insurer access. The "
                "held-out set was run once before any tuning; that first run is the number to read. "
                "The tuned set is shown only to show the tuning worked."
            ),
            does_not_show=r.limit,
        )
    ]


def pathway_metric() -> Metric:
    from bayan.api.app import create_app
    from bayan.core.config import Settings

    app = create_app(Settings(env="dev", demo_mode=True))
    k = app.state.journey.kpis()
    return Metric(
        id="M7",
        title="Pathway timing and referral share on the seeded cases (simulated)",
        status="measured",
        value=(
            f"{k.n_cases} synthetic cases, {k.n_flagged} flagged: median time to result "
            f"{k.time_to_result.median_hours / 24:.1f} days; "
            f"{k.share_referred_within_standard * 100:.0f}% of flagged cases "
            f"({round(k.share_referred_within_standard * k.n_flagged)} of {k.n_flagged}) referred within the standard "
            f"(target {k.referral_target_share * 100:.0f}%)"
        ),
        numeric=k.share_referred_within_standard,
        n=k.n_cases,
        method="Computed from the stored synthetic cases; event times come from a backdated clock.",
        does_not_show=(
            "Real programme performance. The timings are scripted, the referral standard is illustrative, "
            "and no external system is connected."
        ),
    )


def protocol_metrics() -> list[Metric]:
    return [
        Metric(
            id="M8",
            title="Human comprehension (teach-back) study",
            status="not_run",
            value="Not run. A protocol exists; the ethics exemption question is unanswered.",
            method=(
                "Within-subject teach-back on hypothetical couples, five items, stratified by language and a "
                "literacy proxy. At n=30 an 80% score has a 95% interval of 61 to 92%, so the study would be "
                "reported with intervals, never as proof."
            ),
            does_not_show="Everything: no comprehension, uptake or decision-quality claim is made.",
        ),
        Metric(
            id="M9",
            title="Clinical review of rules, detection rates and translations",
            status="not_run",
            value="Not done. Every rule and every Arabic and Urdu string is a draft awaiting sign-off.",
            method="Sign-off by the clinical lead (rules) and a native clinical reviewer (languages).",
            does_not_show="Any clinical validity.",
        ),
    ]


def build_scoreboard(code_version: str = "dev", engine_n: int = ENGINE_N) -> Scoreboard:
    metrics: list[Metric] = []
    metrics += engine_metrics(engine_n)
    metrics += explain_metrics()
    metrics += escalation_metrics()
    metrics += optional_metrics()
    metrics.append(pathway_metric())
    metrics += protocol_metrics()
    return Scoreboard(
        generated_at=datetime.now(UTC),
        code_version=code_version,
        metrics=tuple(metrics),
        caveats=(
            "All people, results and timelines are synthetic. Nothing here measures a real programme.",
            "Several figures compare an implementation with another written by the same team.",
            "Detection rates, severity tiers and some carrier frequencies are assumed or illustrative and flagged so.",
            "Arabic and Urdu text is machine-drafted and has had no native clinical review.",
            "No clinical review, field validation or comprehension study has been done.",
        ),
    )
